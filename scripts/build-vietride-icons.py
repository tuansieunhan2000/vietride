#!/usr/bin/env python3
"""Build/verify a Remix Icon subset using the icon names in VietRide's source.

Requires fontTools[woff] in a temporary virtual environment; see docs/icon-assets.md.
The original Remix CSS, font, selectors, metrics and selected outlines are retained.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / 'fonts' / 'remix'
SOURCE_CSS = FONT_DIR / 'remixicon.css'
SOURCE_FONT = FONT_DIR / 'remixicon.woff2'
OUTPUT_CSS = FONT_DIR / 'vietride-icons.css'
OUTPUT_FONT = FONT_DIR / 'vietride-icons.woff2'
MASK_ICONS = {'ri-zalo-fill'}
# Dynamic calls currently read literal icon names from arrays in these same files.
# New dynamic call sites must be reviewed rather than silently omitting their icons.
DYNAMIC_CALLS = {
    'footer.php': {'$channel[0]'},
    'page-templates/template-home.php': {'$step[0]', '$icon'},
    'template-parts/vietride/guide-list.php': {'$icons[$index]'},
}


def source_files():
    paths = list(ROOT.glob('*.php'))
    for folder in ['inc', 'template-parts', 'page-templates', 'global-templates',
                   'loop-templates', 'sidebar-templates', 'woocommerce']:
        paths += list((ROOT / folder).rglob('*.php'))
    paths += list((ROOT / 'js').glob('vietride*.js'))
    paths += [ROOT / 'src/sass/custom-style.scss']
    return sorted(set(p for p in paths if p.is_file()))


def discover_icons(mapping):
    icons = set()
    for path in source_files():
        source = path.read_text()
        icons.update(re.findall(r'\bri-[a-z0-9-]+', source))
        # Function declarations are not calls; vr_icon() appends the -fill suffix.
        calls_source = re.sub(r'function\s+vr_icon\s*\([^)]*\)', '', source)
        for match in re.finditer(r'\bvr_icon\s*\(([^)]*)\)', calls_source):
            argument = match[1].strip()
            literal = re.fullmatch(r"(['\"])([a-z0-9-]+)\1", argument)
            if literal:
                icons.add('ri-' + literal[2] + '-fill')
                continue
            key = str(path.relative_to(ROOT))
            normalized = re.sub(r'\s+', '', argument)
            assert normalized in DYNAMIC_CALLS.get(key, set()), 'Review dynamic icon call: ' + key + ' ' + argument
            # Include each array's literal value that names a real icon. This also
            # catches newly added icon choices at a reviewed dynamic call site.
            for value in re.findall(r"['\"]([a-z0-9-]+)['\"]", source):
                name = 'ri-' + value + '-fill'
                if name in mapping or name in MASK_ICONS:
                    icons.add(name)
    assert MASK_ICONS.issubset(icons), 'Zalo mask selector unexpectedly missing'
    unknown = icons - set(mapping) - MASK_ICONS
    assert not unknown, 'Unknown icon selector(s): ' + ', '.join(sorted(unknown))
    return sorted(icons - MASK_ICONS)


def css_for_icons(source, mapping, icons):
    base = source[:source.index('.ri-24-hours-fill:before')].rstrip()
    base = base.replace('url("remixicon.woff2")', 'url("vietride-icons.woff2")')
    ranges = ','.join('U+{:X}'.format(mapping[name]) for name in icons)
    base = base.replace('  font-display: swap;', '  font-display: swap;\n  unicode-range: ' + ranges + ';')
    rules = '\n'.join('.' + name + ':before { content: "\\' + format(mapping[name], 'x') + '"; }' for name in icons)
    return base + '\n\n/* Generated by scripts/build-vietride-icons.py. */\n' + rules + '\n'


def verify_font(source, subset, codes):
    from fontTools.pens.recordingPen import RecordingPen
    assert source['head'].unitsPerEm == subset['head'].unitsPerEm, 'Units changed'
    assert source['head'].flags == subset['head'].flags, 'Font origin flags changed'
    for table, fields in [('hhea', ['ascent', 'descent', 'lineGap']),
                          ('OS/2', ['sTypoAscender', 'sTypoDescender', 'sTypoLineGap'])]:
        for field in fields:
            assert getattr(source[table], field) == getattr(subset[table], field), table + '.' + field + ' changed'
    original_map = source.getBestCmap(); subset_map = subset.getBestCmap()
    assert set(subset_map) == set(codes), 'Subset cmap does not match required codepoints'
    original_glyphs = source.getGlyphSet(); subset_glyphs = subset.getGlyphSet()
    for code in codes:
        original_name = original_map[code]; subset_name = subset_map[code]
        assert source['hmtx'][original_name] == subset['hmtx'][subset_name], 'Glyph metrics changed: ' + hex(code)
        for field in ['xMin', 'yMin', 'xMax', 'yMax']:
            assert getattr(source['glyf'][original_name], field) == getattr(subset['glyf'][subset_name], field), 'Glyph bounds changed: ' + hex(code)
        original_pen = RecordingPen(); subset_pen = RecordingPen()
        original_glyphs[original_name].draw(original_pen)
        subset_glyphs[subset_name].draw(subset_pen)
        assert original_pen.value == subset_pen.value, 'Glyph outline changed: ' + hex(code)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated selectors, glyphs and source outline/metric equality without writing')
    args = parser.parse_args()
    source_css = SOURCE_CSS.read_text()
    mapping = {name: int(code, 16) for name, code in re.findall(r'\.(ri-[a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";\s*\}', source_css)}
    icons = discover_icons(mapping)
    codes = {mapping[name] for name in icons}
    expected_css = css_for_icons(source_css, mapping, icons)
    try:
        from fontTools import subset
        from fontTools.ttLib import TTFont
    except ImportError as error:
        raise SystemExit('Install fontTools[woff] in a temporary venv first; see docs/icon-assets.md') from error
    original = TTFont(SOURCE_FONT, recalcTimestamp=False, recalcBBoxes=False)
    assert codes.issubset(original.getBestCmap()), 'Source font missing required glyph'
    if not args.check:
        # Remix's original glyph bounds must remain untouched: recalculating
        # them changes the origin/side-bearing relationship and shifts icons.
        candidate = TTFont(SOURCE_FONT, recalcTimestamp=False, recalcBBoxes=False)
        options = subset.Options()
        options.glyph_names = True
        options.recalc_timestamp = False
        options.flavor = 'woff2'
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=codes)
        subsetter.subset(candidate)
        candidate.flavor = 'woff2'
        candidate.save(OUTPUT_FONT)
        candidate.close()
        OUTPUT_CSS.write_text(expected_css)
    assert OUTPUT_CSS.read_text() == expected_css, 'Generated CSS stale; rebuild subset'
    candidate = TTFont(OUTPUT_FONT, recalcTimestamp=False, recalcBBoxes=False)
    verify_font(original, candidate, codes)
    assert 'font-display: swap;' in expected_css
    assert 'ri-zalo-fill:before' not in expected_css, 'Zalo should keep its existing SVG mask'
    print('PASS {} selectors / {} glyphs: exact outlines, advances and vertical metrics; Zalo mask untouched'.format(len(icons), len(codes)))
    print('CSS: {:,} -> {:,} bytes; WOFF2: {:,} -> {:,} bytes'.format(SOURCE_CSS.stat().st_size, OUTPUT_CSS.stat().st_size, SOURCE_FONT.stat().st_size, OUTPUT_FONT.stat().st_size))
    print('Selectors: ' + ', '.join(icons))
    original.close(); candidate.close()


if __name__ == '__main__':
    main()
